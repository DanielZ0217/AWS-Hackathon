"""The two specialists (chest X-ray, ECG) and the doctor. Each is a Strands agent on Bedrock (Sonnet 4.6).

Anything a number or a rule can decide is decided by plain code (beat counting, red flags). The model
explains what code and the dataset provide, and the radiology agent also looks at the actual X-ray.
`mode="mock"` skips the model entirely and builds the answer from the same data, for offline use.
"""
from __future__ import annotations

import json
import os
import time
from dataclasses import dataclass
from typing import Any, Literal

from pydantic import BaseModel, ValidationError

from . import ecg, redflags
from .cases import Case

SPECIALIST_MODEL = os.environ.get("SPECIALIST_MODEL", "us.anthropic.claude-sonnet-4-6")
DOCTOR_MODEL = os.environ.get("DOCTOR_MODEL", "us.anthropic.claude-sonnet-4-6")
REGION = os.environ.get("AWS_DEFAULT_REGION", "us-east-1")


class MissingInput(Exception):
    """The patient record has no usable data for this specialist. Reported, never guessed."""


class ModelOutputError(Exception):
    """The model's reply could not be read as the expected JSON."""


# --- output shapes -----------------------------------------------------------


class Finding(BaseModel):
    statement: str
    evidence: str = ""


class SpecialistOutput(BaseModel):
    summary: str
    findings: list[Finding] = []
    uncertainty: list[str] = []
    limitations: list[str] = []


class Section(BaseModel):
    title: str
    text: str
    based_on: list[str] = []


class DoctorOutput(BaseModel):
    decision: Literal["proceed", "clarify"]
    reason: str
    sections: list[Section]


@dataclass
class SpecialistInput:
    worker: str
    prompt_data: dict[str, Any]  # the text the model is shown
    images: list[tuple[str, bytes]]  # (format, bytes) pictures the model is shown
    flags: list[dict[str, Any]]  # red flags found by plain code
    gaps: list[dict[str, Any]]  # required values that were missing


@dataclass
class ModelResult:
    output: Any
    call: dict[str, Any]  # model, tokens, duration: the "model call" shown in technical details


# --- building each specialist's input (plain Python) ----------------------------


def build_input(worker: str, case: Case, with_images: bool = True) -> SpecialistInput:
    store, patient, visit = case.store, case.patient, case.visit

    if worker == "radiology":
        try:
            png = store.read(patient.patient_id, visit.xray_file)
        except Exception as exc:  # noqa: BLE001 - any read failure means the input is missing
            raise MissingInput("The chest X-ray file for this visit could not be read.") from exc
        data = {
            "patient": {"age": patient.age, "sex": patient.sex},
            "view": visit.xray.get("view"),
            "reference_label_from_dataset": visit.xray.get("labels", []),
            "reference_label_note": "Made by automated text-mining of a radiology report; it is sometimes wrong.",
        }
        return SpecialistInput("radiology", data, [("png", png)] if with_images else [], redflags.xray_flags(visit), [])

    if worker == "ecg":
        try:
            signal, fs, names = ecg.load_ecg(store, patient.patient_id, visit.ecg_record)
        except Exception as exc:  # noqa: BLE001
            raise MissingInput("The ECG file for this visit could not be read.") from exc
        reported_hr = visit.ecg.get("hr_bpm")
        counted = ecg.summarize(signal, fs, names, reported_hr=reported_hr)
        # Only show the model our own beat count when it agrees with the dataset's rate. A count we
        # do not trust is left out and said so, instead of being handed over as a measurement.
        trusted = counted.heart_rate_bpm is not None and not counted.notes
        flags, gaps = redflags.ecg_flags(visit)
        data = {
            "measurements_from_dataset": {
                "heart_rate_bpm": reported_hr,
                "pr_ms": visit.ecg.get("pr_ms"),
                "qrs_ms": visit.ecg.get("qrs_ms"),
                "qt_ms": visit.ecg.get("qt_ms"),
                "qrs_axis_degrees": visit.ecg.get("qrs_axis"),
            },
            "machine_generated_report": visit.ecg.get("machine_report"),
            "report_note": "Generated by the ECG machine, not confirmed by a cardiologist. Such reports are often over-cautious.",
            "beats_counted_from_trace": (
                {"heart_rate_bpm": counted.heart_rate_bpm, "irregularity": counted.rr_irregularity, "beats": counted.beats_detected}
                if trusted
                else "Automatic beat counting on this trace was not reliable, so use the dataset's rate."
            ),
        }
        images = [("png", ecg.render_png(signal, fs, names))] if with_images else []
        return SpecialistInput("ecg", data, images, flags, gaps)

    raise ValueError(f"unknown worker {worker!r}")


# --- prompts --------------------------------------------------------------------

_COMMON = """You are a specialist assistant in a hackathon prototype that explains PUBLIC research data to a caregiver.
You are not a doctor. Do not diagnose, and do not mention medicines, doses, or treatment changes.
Use ONLY the data provided and never invent values. If something is missing or unclear, say so under "limitations".
Use cautious wording such as "may" or "could". Write in plain language a 12-year-old could follow.
Reply with a single JSON object and nothing else (no markdown), exactly in this form:
{"summary": "<one plain sentence>", "findings": [{"statement": "<plain sentence>", "evidence": "<the value or phrase it rests on>"}], "uncertainty": ["<what is uncertain>"], "limitations": ["<what you could not tell>"]}
Give at most 3 findings."""

PROMPTS = {
    "radiology": _COMMON
    + """
Your job: describe what the chest X-ray shows. You are given the image itself and a reference label from the dataset.
Describe what you can see about the size of the heart, the lungs, and any fluid. Say whether what you see fits the reference label.
Say plainly under limitations that this is one front-view picture read by an AI model, not by a radiologist.""",
    "ecg": _COMMON
    + """
Your job: explain the heart tracing (ECG). You are given measurements from the dataset, a machine-generated report, and a picture of 4 of the 12 leads.
Explain the heart rate, the rhythm, and what the machine report says, in plain words. The report was written by the ECG machine and not confirmed by a cardiologist; say so under limitations.""",
}

_DOCTOR_PROMPT = """You are the doctor-style synthesizer in a hackathon prototype that explains PUBLIC research data to a caregiver. You are not a doctor.
You receive the findings from the specialists (chest X-ray and ECG), a list of any parts that could not be reviewed, and the facts from EARLIER visits if there were any. Combine them into a short summary.
Rules: use ONLY what you are given; never invent values; no diagnosis; no medicine names, doses, or treatment changes; cautious wording ("may", "could"); plain language a 12-year-old could follow.
If earlier visits are given, say in "What the findings may mean" how this visit looks compared with them, using only the facts given (for example, the report no longer mentions something).
If any part could not be reviewed, say plainly that the summary does not cover it.
Reply with a single JSON object and nothing else (no markdown), exactly in this form:
{"decision": "proceed" or "clarify", "reason": "<one sentence>", "sections": [{"title": "...", "text": "<2 to 4 short sentences>", "based_on": ["radiology", "ecg"]}]}
Use exactly these four section titles, in this order: "What was reviewed", "What the findings may mean", "Everyday habits to discuss", "Questions to ask your doctor".
"Everyday habits to discuss" may only suggest nutrition and gentle-movement topics to talk about with the care team, not instructions.
The last section must remind the reader this is a prototype, not medical advice. "based_on" lists only the specialists a section rests on."""

# --- talking to the model ------------------------------------------------------


def _parse_json(text: str) -> dict[str, Any]:
    start, end = text.find("{"), text.rfind("}")
    if start < 0 or end <= start:
        raise ModelOutputError("the model reply had no JSON object")
    try:
        return json.loads(text[start : end + 1])
    except json.JSONDecodeError as exc:
        raise ModelOutputError(f"the model reply was not valid JSON: {exc}") from exc


async def _ask(model_id: str, system_prompt: str, user_content: Any, max_tokens: int) -> tuple[str, dict[str, Any]]:
    from strands import Agent  # imported here so mock mode needs no AWS libraries
    from strands.models import BedrockModel

    agent = Agent(
        model=BedrockModel(model_id=model_id, region_name=REGION, temperature=0.2, max_tokens=max_tokens),
        system_prompt=system_prompt,
        callback_handler=None,  # no console output
    )
    started = time.perf_counter()
    result = await agent.invoke_async(user_content)
    usage = result.metrics.accumulated_usage
    call = {
        "model": model_id,
        "input_tokens": usage.get("inputTokens"),
        "output_tokens": usage.get("outputTokens"),
        "duration_ms": int((time.perf_counter() - started) * 1000),
    }
    return str(result), call


async def run_specialist(spec: SpecialistInput, mode: str) -> ModelResult:
    if mode == "mock":
        return ModelResult(_mock_specialist(spec), {"model": "mock", "input_tokens": None, "output_tokens": None, "duration_ms": 0})
    text_block = {"text": json.dumps(spec.prompt_data, indent=2)}
    content: Any = [text_block, *({"image": {"format": fmt, "source": {"bytes": data}}} for fmt, data in spec.images)]
    reply, call = await _ask(SPECIALIST_MODEL, PROMPTS[spec.worker], content, 800)
    try:
        return ModelResult(SpecialistOutput.model_validate(_parse_json(reply)), call)
    except ValidationError as exc:
        raise ModelOutputError(f"the model reply did not match the expected shape: {exc.error_count()} problem(s)") from exc


async def run_doctor(results: dict[str, SpecialistOutput], missing: list[str], earlier: list[dict[str, Any]], mode: str) -> ModelResult:
    if mode == "mock":
        return ModelResult(_mock_doctor(results, missing, earlier), {"model": "mock", "input_tokens": None, "output_tokens": None, "duration_ms": 0})
    payload = {
        "specialists": {worker: out.model_dump() for worker, out in results.items()},
        "could_not_be_reviewed": missing,
        "earlier_visits": earlier,
    }
    reply, call = await _ask(DOCTOR_MODEL, _DOCTOR_PROMPT, json.dumps(payload, indent=2), 1500)
    try:
        return ModelResult(DoctorOutput.model_validate(_parse_json(reply)), call)
    except ValidationError as exc:
        raise ModelOutputError(f"the model reply did not match the expected shape: {exc.error_count()} problem(s)") from exc


# --- mock mode (no model): built from the same data ----------------------------


def _mock_specialist(spec: SpecialistInput) -> SpecialistOutput:
    if spec.worker == "radiology":
        labels = ", ".join(spec.prompt_data["reference_label_from_dataset"]) or "no finding"
        return SpecialistOutput(
            summary=f"The reference label for this chest X-ray is: {labels}.",
            findings=[Finding(statement=f"The dataset labels this X-ray: {labels}.", evidence="reference label")],
            uncertainty=["The label comes from automated text-mining and can be wrong."],
            limitations=["Mock mode: the image was not looked at and no model was used."],
        )
    report = spec.prompt_data.get("machine_generated_report") or "no report"
    rate = spec.prompt_data["measurements_from_dataset"]["heart_rate_bpm"]
    return SpecialistOutput(
        summary=f"The ECG machine measured a heart rate of {rate:.0f} per minute.",
        findings=[Finding(statement=f"The machine report says: {report}", evidence="machine-generated report")],
        uncertainty=["The report was written by the ECG machine and not confirmed by a cardiologist."],
        limitations=["Mock mode: no model was used."],
    )


def _mock_doctor(results: dict[str, SpecialistOutput], missing: list[str], earlier: list[dict[str, Any]]) -> DoctorOutput:
    names = {"radiology": "chest X-ray", "ecg": "ECG"}
    reviewed = " and ".join(names[w] for w in results)
    gap = f" The {', '.join(names[w] for w in missing)} could not be reviewed, so this summary does not cover it." if missing else ""
    trend = " Earlier visits are available for comparison." if earlier else ""
    return DoctorOutput(
        decision="clarify" if missing else "proceed",
        reason="Part of the review is missing." if missing else "Both specialists returned usable findings.",
        sections=[
            Section(title="What was reviewed", text=f"The care team reviewed the {reviewed}.{gap}", based_on=list(results)),
            Section(title="What the findings may mean", text="Some results may be worth discussing with a clinician. Nothing here is a diagnosis." + trend, based_on=list(results)),
            Section(title="Everyday habits to discuss", text="Ask your care team about food and gentle movement that suit you.", based_on=[]),
            Section(title="Questions to ask your doctor", text="Bring these results to a healthcare professional. This is a prototype and not medical advice.", based_on=[]),
        ],
    )
